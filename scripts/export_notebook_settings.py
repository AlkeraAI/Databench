"""Export the notebook settings schema for the portal.

``alkera_notebook.format.settings`` owns every notebook setting and each cell
kind's (type, values, default, label, control, effect). This writes it as
``packages/shared-openapi/notebook-settings.json`` and as the TypeScript
module ``packages/notebook-ui/src/generated/notebookSettings.ts`` the settings
form renders, so a new setting is a schema entry, never a UI change. Run by
``make gen-notebook-settings`` (chained into ``make gen-sdk``); the drift job
fails on a stale copy.
"""

from __future__ import annotations

import json
from pathlib import Path

from alkera_notebook.format.settings import export_schema

ROOT = Path(__file__).resolve().parents[1]
JSON_OUT = ROOT / "packages" / "shared-openapi" / "notebook-settings.json"
TS_OUT = ROOT / "packages" / "notebook-ui" / "src" / "generated" / "notebookSettings.ts"

TS_HEADER = """\
// Generated by scripts/export_notebook_settings.py from
// alkera_notebook.format.settings. Do not edit; run `make gen-notebook-settings`.
import type { NotebookSettingsSchema } from "../model/settings";

export const NOTEBOOK_SETTINGS_SCHEMA: NotebookSettingsSchema = """


def main() -> None:
    text = json.dumps(export_schema(), indent=2, ensure_ascii=False) + "\n"
    JSON_OUT.write_text(text, encoding="utf-8")
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text(TS_HEADER + text.rstrip("\n") + ";\n", encoding="utf-8")
    print(f"wrote {JSON_OUT.relative_to(ROOT)} and {TS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
