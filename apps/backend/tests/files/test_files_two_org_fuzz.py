@dataclass(frozen=True, slots=True)
class Attacker:
    """One of org B's principals, with the headers that identify it."""

    name: str
    client: AsyncClient
    headers: Mapping[str, str]
    #: Whether the Files surface accepts this credential at all, measured
    #: against the attacker's OWN org rather than assumed. A credential the
    #: surface refuses answers 401 before it reads a byte of anything, which is
    #: no oracle — but it has to refuse *uniformly*, or the one route that let
    #: it through is the hole. Both halves are asserted below.
    accepted: bool = True


def _fresh_client() -> AsyncClient:
    """A client that reports a crash as the 500 a real server would send.

    ``raise_app_exceptions`` defaults to re-raising, which would turn an
    unhandled error into a test error and hide *which* status the adversary
    saw; behind uvicorn the attacker sees a 500, and a 500 is itself a signal
    the id reached code that expected it to resolve.
    """
    return AsyncClient(
        transport=ASGITransport(app=fastapi_app, raise_app_exceptions=False),
        base_url="http://test",
        # The suite's `app_client` cannot be borrowed here -- it owns its
        # transport, and this one has to keep `raise_app_exceptions=False` --
        # so the browser evidence the origin guard demands of a
        # cookie-authenticated mutation is spelled out instead. Without it
        # every non-safe probe below is refused by the guard before it reaches
        # a route, and the fuzz would be measuring the middleware rather than
        # org isolation.
        headers={"Origin": settings.frontend_base_url},
    )


