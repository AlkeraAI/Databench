@pytest.mark.asyncio
async def test_a_real_signed_url_refuses_a_claim_rewritten_for_org_b(
    victim: VictimTree,
    fx: FilesFixtures,
    real_session: AsyncSession,
    stranger_org: tuple[uuid.UUID, uuid.UUID],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A live grant of A's, re-pointed at B, is the 404 a bogus token gets.

    The fuzz elsewhere aims random tokens at this route, which never reach the
    signature check at all. This one mints the real thing and then rewrites the
    claim, so the assertion is about the HMAC covering the claim rather than
    about a token that names nothing. The grant row is the other half: a forged
    claim must not even consume it, or a refused request would still burn a
    single-use URL of somebody else's.
    """
    from alkera_core.files.clock import SystemClock
    from alkera_core.files.ids import OrgScope, VersionId
    from alkera_core.files.repo import FilesRepo
    from alkera_core.files.signed_urls import CONTENT_PATH_PREFIX, mint_content_url

    monkeypatch.setattr(settings, "files_content_base_url", f"http://{FUZZ_CONTENT_HOST}")
    org_b, user_b = stranger_org
    repo = FilesRepo(real_session, OrgScope(org_team_id=fx.org_team_id))
    key = settings.effective_files_content_signing_key.encode()
    url = await mint_content_url(
        repo,
        version_id=VersionId(uuid.UUID(victim.version_id)),
        session_id=None,
        clock=SystemClock(),
        key=key,
        user_id=fx.actor_id,
    )
    await real_session.commit()
    token = url.removeprefix(CONTENT_PATH_PREFIX)
    bogus = f"{uuid.uuid4().hex}{uuid.uuid4().hex}.Y2xhaW0.{'f' * 64}"

    client = _fresh_client()
    try:
        forged = await client.get(
            f"{CONTENT_MOUNT}/{_reclaim(token, org_id=org_b, user_id=user_b)}",
            headers={"Host": FUZZ_CONTENT_HOST},
        )
        nothing = await client.get(f"{CONTENT_MOUNT}/{bogus}", headers={"Host": FUZZ_CONTENT_HOST})
    finally:
        await client.aclose()

    assert forged.status_code == nothing.status_code == 404
    assert forged.content == nothing.content == b'{"code":"not_found"}'
    unused = await real_session.execute(
        text("SELECT used_at FROM file_content_grants WHERE nonce = :n"),
        {"n": token.partition(".")[0]},
    )
    assert unused.scalar_one() is None, "a forged claim consumed somebody else's grant"


@pytest.mark.asyncio
async def test_a_real_archive_claim_refuses_being_rewritten_for_org_b(
    victim: VictimTree,
    fx: FilesFixtures,
    real_session: AsyncSession,
    stranger_org: tuple[uuid.UUID, uuid.UUID],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The archive's twin: a real claim re-signed for nobody is a bogus token.

    Same shape as the content case — the token is minted for A's real operation
    and subtree, then its org and user are swapped for B's while the signature
    stays A's.
    """
    from backend.services.files.archive import ArchiveClaim, sign_claim

    monkeypatch.setattr(settings, "files_content_base_url", f"http://{FUZZ_CONTENT_HOST}")
    org_b, user_b = stranger_org
    key = settings.effective_files_content_signing_key.encode()
    expires = datetime.now(UTC) + timedelta(minutes=10)
    mine = ArchiveClaim(
        operation_id=uuid.UUID(victim.operation_id),
        node_id=uuid.UUID(victim.folder_id),
        org_id=fx.org_team_id,
        user_id=fx.actor_id,
        expires_at=expires,
    )
    theirs = ArchiveClaim(
        operation_id=mine.operation_id,
        node_id=mine.node_id,
        org_id=org_b,
        user_id=user_b,
        expires_at=expires,
    )
    #: B's claim carrying A's signature: the payload changed, the HMAC did not.
    forged_token = (
        f"{sign_claim(theirs, key).partition('.')[0]}.{sign_claim(mine, key).rpartition('.')[2]}"
    )
    bogus = f"{uuid.uuid4().hex}.{'f' * 64}"

    client = _fresh_client()
    try:
        forged = await client.get(
            f"{CONTENT_MOUNT}/archive/{forged_token}", headers={"Host": FUZZ_CONTENT_HOST}
        )
        nothing = await client.get(
            f"{CONTENT_MOUNT}/archive/{bogus}", headers={"Host": FUZZ_CONTENT_HOST}
        )
    finally:
        await client.aclose()

    assert forged.status_code == nothing.status_code == 404
    assert forged.content == nothing.content == b'{"code":"not_found"}'
