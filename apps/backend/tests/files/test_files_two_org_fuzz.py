API_PREFIX: Final = "/api/v1/files"
CONTENT_MOUNT: Final = "/c"

#: Every route the fuzz drives. Pinned so a new Files route — or a new content
#: route — cannot join the surface without joining the adversary's list too.
#: Raise it in the same commit that adds the route, having checked the route
#: appears below with real ids substituted into its path.
EXPECTED_ROUTE_COUNT: Final = 64

#: How many of those name a resource in their path and so can be aimed at org
#: A's ids. The rest answer about the caller's own org and are held to the
#: weaker (but still binding) "leaks nothing of A's" bar. Only ``GET /drives``
#: and ``POST /uploads`` are parameterless, and the notebook output frame's
#: only parameter names an app build (see :data:`BUILD_PARAMS`), so this is the
#: count minus three.
EXPECTED_TARGETED_COUNT: Final = 61

#: Path parameters that name no tenant's resource: the notebook output frame is
#: one page per app build, served alike to everyone, so its path cannot be
#: aimed at org A and is held to the "leaks nothing" bar instead.
BUILD_PARAMS: Final = ("{build_hash}",)

#: The build the fuzz names in the output frame's path (any lower-case hex).
FUZZ_BUILD_HASH: Final = "0123456789abcdef"

#: Paths whose routes refuse a caller that holds no lease fence before they
#: resolve anything — the snapshot write, both halves of the live plane and the
#: holder's tree report. A request without the epoch headers is turned away at
#: the fence and never reaches the isolation the fuzz is here to measure. The
#: walk's digest request is fenced the same way.
FENCED_SUFFIXES: Final = ("/snapshots", "/lease/live", "/lease/tree", "/lease/tree/digests")

#: The rotation that puts the holder-reported row in the item slot: its
#: position in :meth:`VictimTree.item_ids`.
REPORTED_ROTATION: Final = 4

#: The one body a "not yours" answer may carry (``_errors.NOT_FOUND_BODY``).

#: Routes that today answer something other than the opaque 404 for a resource
#: in another org, with the reason and the owner. A ratchet: the fuzz asserts
#: each one is still broken, so closing the gap turns this test red until the
#: entry is deleted. Nothing is added here without a report to the owning lane.
KNOWN_CONTRACT_GAPS: Final[dict[str, str]] = {}


@dataclass(frozen=True, slots=True)
class RouteSpec:
    """One method+path pair from the app, with its JSON request schema."""

    method: str
    path: str
    body_schema: dict[str, Any] | None
    wants_bytes: bool

    @property
    def name(self) -> str:
        return f"{self.method} {self.path}"

    @property
    def targeted(self) -> bool:
        """Whether the path names a resource, and so can be aimed at org A.

        A parameterless route (``GET /drives``, ``POST /uploads``) answers about
        the caller's *own* org: a ``404`` there would be a bug, not isolation.
        Those routes still have to leak nothing, which is asserted separately.
        """
        path = self.path
        for param in BUILD_PARAMS:
            path = path.replace(param, "")
        return "{" in path


def _operation_body(spec: Mapping[str, Any], path: str, method: str) -> tuple[Any, bool]:
    """``(json schema, wants raw bytes)`` for one operation in the OpenAPI doc."""
    operation = spec.get("paths", {}).get(path, {}).get(method.lower())
    if not isinstance(operation, dict):
        return None, False
    body = operation.get("requestBody")
    if not isinstance(body, dict):
        return None, False
    content = body.get("content", {})
    if "application/json" in content:
        return content["application/json"].get("schema"), False
    return None, bool(content)


def _collect_routes() -> tuple[RouteSpec, ...]:
    """Every Files route the running app serves, read from its route table."""
    spec = fastapi_app.openapi()
    found: list[RouteSpec] = []
    for route in fastapi_app.routes:
        if isinstance(route, Mount) and route.path == CONTENT_MOUNT:
            for sub in route.routes:
                if not isinstance(sub, APIRoute):
                    continue
                path = sub.path if sub.path.startswith(CONTENT_MOUNT) else CONTENT_MOUNT + sub.path
                for method in sorted(sub.methods - {"HEAD", "OPTIONS"}):
                    found.append(RouteSpec(method, path, None, False))
        elif isinstance(route, APIRoute) and route.path.startswith(API_PREFIX):
            for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
                schema, raw = _operation_body(spec, route.path, method)
                found.append(RouteSpec(method, route.path, schema, raw))
    return tuple(sorted(found, key=lambda route: (route.path, route.method)))


ROUTES: Final = _collect_routes()


