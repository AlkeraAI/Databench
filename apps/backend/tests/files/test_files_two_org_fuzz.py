async def test_every_files_route_is_in_the_fuzz() -> None:
    """The adversary's list is the app's list.

    Pinned rather than merely derived: a derived count would silently absorb a
    new route, which is exactly the route most likely to have been written
    without the isolation contract in mind.
    """
    listing = "\n".join(route.name for route in ROUTES)
    assert len(ROUTES) == EXPECTED_ROUTE_COUNT, (
        f"{len(ROUTES)} Files routes are served but the fuzz pins "
        f"{EXPECTED_ROUTE_COUNT}; add the route's ids to VictimTree/_fill and "
        f"raise the pin:\n{listing}"
    )
    assert any(route.path.startswith(CONTENT_MOUNT) for route in ROUTES)
    assert any(route.method != "GET" for route in ROUTES)
    assert sum(1 for route in ROUTES if route.targeted) == EXPECTED_TARGETED_COUNT, (
        "a route that names a resource joined the surface without joining the "
        f"aimed-at-org-A half of the fuzz:\n{listing}"
    )


@pytest.mark.parametrize("route", ROUTES, ids=lambda route: route.name)
async def test_org_b_gets_the_same_opaque_404_from_every_route(
    route: RouteSpec,
    victim: VictimTree,
    attackers: tuple[Attacker, ...],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Every route, every principal, schema-valid nonsense: ``404`` and nothing else.

    The rate limiter is off for this one: the fuzz fires far more requests from
    one address than a real caller would, and a ``429`` would mask the answer
    under test. Its own property is asserted separately below.
    """
    monkeypatch.setattr(settings, "rate_limit_enabled", False)
    nowhere = VictimTree.nonexistent()
    bodies = bodies_for(route, 2)
    # Every route is also aimed once at the row the holder's report minted,
    # which the two rotations above would otherwise never reach.
    for index, body in [*enumerate(bodies), (REPORTED_ROTATION, bodies[0])]:
        aimed = _fill(route.path, victim, index) + _query(route)
        elsewhere = _fill(route.path, nowhere, index) + _query(route)
        for attacker in attackers:
            response = await _fire(route, attacker, aimed, body)
            text = response.text
            leaked = _leaks(text, [*victim.secrets, *victim.all_ids()])
            assert leaked is None, f"{route.name} leaked {leaked!r} to {attacker.name}"
            if not attacker.accepted and route.path.startswith(API_PREFIX):
                assert response.status_code == 401, (
                    f"{route.name} let {attacker.name} past a credential every "
                    f"other Files route refuses: {response.status_code} {text[:200]}"
                )
                continue
            if not route.targeted:
                assert response.status_code < 500, (
                    f"{route.name} answered {attacker.name} with "
                    f"{response.status_code}: {text[:200]}"
                )
                continue

            # The same request, aimed at ids that exist nowhere. Anything the
            # two answers do not share — a status, a code, a field — is the
            # oracle being guarded against, whatever the status happens to be.
            twin = await _fire(route, attacker, elsewhere, body)
            assert (response.status_code, _stable(text)) == (
                twin.status_code,
                _stable(twin.text),
            ), (
                f"{route.name} distinguishes org A's ids from ids that exist "
                f"nowhere for {attacker.name}: {response.status_code} "
                f"{text[:160]} vs {twin.status_code} {twin.text[:160]}"
            )

            if route.name in KNOWN_CONTRACT_GAPS:
                # A ratchet, not a silence: the day the owning lane makes this
                # route answer 404 this assertion fails and the entry — with
                # its reason — is deleted.
                assert response.status_code != 404, (
                    f"{route.name} now answers 404; delete its KNOWN_CONTRACT_GAPS entry"
                )
                continue
            assert response.status_code != 403, (
                f"{route.name} told {attacker.name} that A's resource exists: 403 {text[:200]}"
            )
            assert response.status_code < 500, (
                f"{route.name} answered {attacker.name} with {response.status_code}: {text[:200]}"
            )
            assert response.status_code == 404, (
                f"{route.name} answered {attacker.name} with {response.status_code}: {text[:200]}"
            )
            if text:
                assert _opaque(response), (
                    f"{route.name} answered {attacker.name} with a body other than "
                    f"the opaque one: {text[:200]}"
                )


def _opaque(response: Response) -> bool:
    """Whether ``response`` is the one opaque refusal its surface answers: the
    error envelope on the API, the flat body on the content plane, which is a
    registered exception to the envelope."""
    body = response.json()
    if response.url.path.startswith("/c/"):
        return bool(body == {"code": "not_found"})
    return "error" in body and refusal(response) == NOT_FOUND


async def test_the_lease_listing_answers_an_agent_without_resolving_its_id(
    client: AsyncClient,
    files_org: FilesOrgFixture,
    files_on: None,
) -> None:
    """An agent asserting into its own org gets an answer, not a 500.

    A lease is held by a user id; an agent asserts a session id, which is not
    one. The listing used to parse it as a UUID before it had resolved anything,
    so an agent asking about its own org's drive got a 500 — and a 500 on a real
    drive next to a 404 on a stranger's is itself the oracle this route family
    is meant to deny. The truthful answer is that none of the leases are the
    agent's, and a drive that is not this org's is still simply not there.
    """
    caller = await login(_fresh_client(), files_org.member.email, files_org.member_password or "")
    try:
        # The drive is ensured by the member acting for themselves: creating one
        # under an agent assertion trips a separate, out-of-lane parse of the
        # same id in the history writer, and this test is about the listing.
        drive = await caller.get(f"{API_PREFIX}/drives")
        assert drive.status_code == 200, drive.text
        drive_id = drive.json()["id"]
        headers = dict(agent_headers("sess-listing"))

        mine = await caller.get(f"{API_PREFIX}/drives/{drive_id}/leases?mine=true", headers=headers)
        assert mine.status_code == 200, mine.text
        assert mine.json() == []

        stranger = await caller.get(
            f"{API_PREFIX}/drives/{uuid.uuid4()}/leases?mine=true", headers=headers
        )
        assert stranger.status_code == 404, stranger.text
        assert refusal(stranger) == NOT_FOUND
    finally:
        await caller.aclose()


async def _quota_snapshot(session: AsyncSession, org_id: uuid.UUID) -> dict[str, Any]:
    """Every number org A's bill is computed from."""
    drives = (
        (await session.execute(select(FileDrive).where(FileDrive.org_team_id == org_id)))
        .scalars()
        .all()
    )
    snapshot: dict[str, Any] = {
        f"drive:{row.id}": (row.quota_bytes, row.quota_nodes, row.next_ino) for row in drives
    }
    for table in Base.metadata.sorted_tables:
        if "billable_bytes" not in table.columns or "org_team_id" not in table.columns:
            continue
        rows = await session.execute(
            select(table.c.billable_bytes).where(table.c.org_team_id == org_id)
        )
        snapshot[f"billable:{table.name}"] = sorted(str(value) for (value,) in rows)
    return snapshot


async def test_org_b_traffic_never_moves_org_a_quota_or_billable_bytes(
    real_session: AsyncSession,
    files_org: FilesOrgFixture,
    victim: VictimTree,
    attackers: tuple[Attacker, ...],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A stranger's failed requests are not billed to the org they aimed at.

    Not merely "the bill did not grow": the whole quota picture is compared, so
    a route that reserved and then released would still be caught by a moved
    ``next_ino`` — the counter a reservation burns and cannot give back.
    """
    monkeypatch.setattr(settings, "rate_limit_enabled", False)
    org_id = files_org.org.org_id
    before = await _quota_snapshot(real_session, org_id)
    for index, route in enumerate(ROUTES):
        url = _fill(route.path, victim, index) + _query(route)
        body = bodies_for(route, 1)[0]
        for attacker in attackers:
            await _fire(route, attacker, url, body)
    real_session.expire_all()
    after = await _quota_snapshot(real_session, org_id)
    assert after == before


async def test_org_b_exhausting_its_rate_limit_does_not_throttle_org_a(
    victim: VictimTree,
    files_client: AsyncClient,
    attackers: tuple[Attacker, ...],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A ``429`` from one org never reflects another's traffic.

    Fired at the drives listing, whose bucket A is about to use: 50 requests
    from B, then A's own request must be answered on its merits. A shared
    bucket makes A's answer a ``429`` — B's traffic, on A's bill, in A's
    latency.
    """
    monkeypatch.setattr(settings, "rate_limit_enabled", True)
    url = f"{API_PREFIX}/drives"
    attacker = attackers[0]
    for _ in range(50):
        await attacker.client.get(url, headers=dict(attacker.headers))
    response = await files_client.get(url)
    assert response.status_code != 429, "org B's burst throttled org A: the buckets are shared"


# --------------------------------------------------------------------------
# Real tokens, not random ones: the claim inside a signed URL is not a lever.
# --------------------------------------------------------------------------

FUZZ_CONTENT_HOST: Final = "files.fuzz.localhost:8000"


def _reclaim(token: str, *, org_id: uuid.UUID, user_id: uuid.UUID) -> str:
    """``token`` with org B substituted into its claim, signature untouched.

    This is the attack a random token cannot express: the adversary holds a
    real, live, unexpired URL and edits the only part of it that says whose
    access to resolve.
    """
    import base64

    nonce, _, rest = token.partition(".")
    signature = rest.rpartition(".")[2]
    # Encoded here rather than through the module's own encoder, so the test
    # would still catch a claim format that silently stopped being covered.
    raw = b"\x1f".join((str(org_id).encode(), str(user_id).encode(), b""))
    forged = base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")
    return f"{nonce}.{forged}.{signature}"


