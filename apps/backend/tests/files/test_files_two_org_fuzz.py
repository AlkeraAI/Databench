@dataclass
class VictimTree:
    """Org A's real ids — everything a path parameter could name."""

    drive_id: str
    folder_id: str
    file_id: str
    object_id: str
    leased_folder_id: str
    version_id: str
    session_id: str
    operation_id: str
    share_id: str
    token: str
    #: A file the holder's tree report minted: a row with no bytes, reached by
    #: a path no other row source takes.
    reported_file_id: str
    #: A conflict the drive settled itself on A's file: a row that names two
    #: writers by name and a copy node, reached only through the conflicts pane.
    conflict_id: str
    secrets: tuple[str, ...] = field(default_factory=tuple)

    @classmethod
    def nonexistent(cls) -> VictimTree:
        """The control: ids that name nothing, anywhere, in any org.

        The fuzz compares A's answer with this one, so a route that merely
        *looks* refused — a 422 from a validator, say — still has to refuse
        identically, and cannot become the oracle the 404 was not.
        """
        ids = [uuid.uuid4().hex for _ in range(12)]
        return cls(*ids, secrets=())

    def item_ids(self) -> tuple[str, ...]:
        return (
            self.file_id,
            self.folder_id,
            self.object_id,
            self.leased_folder_id,
            self.reported_file_id,
        )

    def all_ids(self) -> tuple[str, ...]:
        return (
            self.drive_id,
            *self.item_ids(),
            self.version_id,
            self.session_id,
            self.operation_id,
            self.share_id,
            self.token,
            self.conflict_id,
        )


