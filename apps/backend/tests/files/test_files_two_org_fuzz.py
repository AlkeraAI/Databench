def _fill(path: str, tree: VictimTree, rotation: int) -> str:
    """``path`` with every parameter replaced by one of A's real ids."""
    items = tree.item_ids()
    replacements = {
        "{drive_id}": tree.drive_id,
        "{item_id}": items[rotation % len(items)],
        "{node_id}": items[(rotation + 1) % len(items)],
        "{session_id}": tree.session_id,
        "{operation_id}": tree.operation_id,
        "{op_id}": tree.operation_id,
        "{conflict_id}": tree.conflict_id,
        "{share_id}": tree.share_id,
        "{version_id}": tree.version_id,
        "{token}": tree.token,
        "{part_no}": "1",
        "{path:path}": "assets/chart.png",
        "{item_path:path}": "budgets/acquisition-memo.txt",
        "{build_hash}": FUZZ_BUILD_HASH,
    }
    filled = path
    for placeholder, value in replacements.items():
        filled = filled.replace(placeholder, value)
    assert "{" not in filled, f"unfilled path parameter in {path}"
    return filled


def _headers(route: RouteSpec, attacker: Attacker) -> dict[str, str]:
    """The preconditions the route requires before it will look at anything.

    A request refused for a missing header never reaches the policy, so the
    fuzz sends every precondition a legitimate caller would: the idempotency
    key, the ``If-Match``, and — on a fenced route — the lease headers.
    """
    sent = dict(attacker.headers)
    if route.method != "GET":
        sent["Idempotency-Key"] = uuid.uuid4().hex
        sent["If-Match"] = '"1"'
    if route.path.endswith(FENCED_SUFFIXES):
        sent["X-Alkera-Lease-Epoch"] = "1"
        sent["X-Alkera-Lease-Instance"] = uuid.uuid4().hex
    return sent


def _query(route: RouteSpec) -> str:
    """The query string a route refuses to answer without."""
    return "?mine=true" if route.path.endswith("/leases") else ""


async def _fire(route: RouteSpec, attacker: Attacker, url: str, body: Any) -> Response:
    headers = _headers(route, attacker)
    if route.wants_bytes:
        return await attacker.client.request(
            route.method, url, content=b"stranger", headers=headers
        )
    return await attacker.client.request(route.method, url, json=body, headers=headers)


#: Fields a body legitimately varies between two requests. Everything else in
#: a refusal must match, or it is the oracle.
_VOLATILE_BODY = re.compile(r'"(?:trace_id|request_id|retry_after)":\s*("[^"]*"|[0-9.]+)')


def _stable(text: str) -> str:
    """``text`` with the per-request fields blanked, ready to compare."""
    return _VOLATILE_BODY.sub('"volatile":null', text)


def _leaks(text: str, secrets: Iterable[str]) -> str | None:
    for secret in secrets:
        if secret and secret in text:
            return secret
    return None


