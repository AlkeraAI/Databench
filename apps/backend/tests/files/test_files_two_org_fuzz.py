def _resolve(schema: Any, defs: Mapping[str, Any]) -> Any:
    while isinstance(schema, dict) and "$ref" in schema:
        ref = str(schema["$ref"]).rsplit("/", 1)[-1]
        schema = defs.get(ref, {})
    return schema


#: Fields whose *values* have a vocabulary the JSON Schema does not carry.
#: Without these the generator sends a random word where the library expects an
#: enum, the request dies in validation, and the route under test is never
#: reached — a fuzz that never gets past the door proves nothing.
_FIELD_VOCABULARY: Final[dict[str, tuple[str, ...]]] = {
    "principalKind": ("user", "team", "org"),
    "principal.kind": ("user", "team", "org"),
    "role": ("reader", "writer", "manager"),
    "conflictBehavior": ("fail", "rename", "replace"),
    "kind": ("file", "folder"),
    "purpose": ("mount", "stage"),
}


def _join(parent: str, key: str) -> str:
    """The dotted name of a nested field, so ``principal.kind`` and a bare
    ``kind`` can have different vocabularies."""
    return f"{parent}.{key}" if parent else key


def _strategy(
    schema: Any, defs: Mapping[str, Any], depth: int = 0, name: str = ""
) -> st.SearchStrategy[Any]:
    """A strategy generating values that validate against ``schema``.

    Only the JSON-Schema subset FastAPI emits is handled; anything unrecognised
    degrades to ``None``, which is what an absent optional field looks like on
    the wire and so never turns a 404 into a 422.
    """
    schema = _resolve(schema, defs)
    if not isinstance(schema, dict) or depth > 4:
        return st.none()
    if "enum" in schema:
        return st.sampled_from(list(schema["enum"]))
    if "const" in schema:
        return st.just(schema["const"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return st.one_of([_strategy(option, defs, depth + 1, name) for option in schema[key]])
    if "allOf" in schema:
        return _strategy(schema["allOf"][0], defs, depth + 1, name)
    kind = schema.get("type")
    if kind == "object":
        properties = schema.get("properties", {})
        required = set(schema.get("required", ()))
        mapping = {
            key: _strategy(sub, defs, depth + 1, _join(name, key))
            for key, sub in properties.items()
            if key in required
        }
        optional = {
            key: _strategy(sub, defs, depth + 1, _join(name, key))
            for key, sub in properties.items()
            if key not in required
        }
        return st.fixed_dictionaries(mapping, optional=optional)
    if kind == "array":
        return st.lists(_strategy(schema.get("items", {}), defs, depth + 1, name), max_size=2)
    if kind == "string":
        if name.rsplit(".", 1)[-1] == name and name in _FIELD_VOCABULARY:
            return st.sampled_from(_FIELD_VOCABULARY[name])
        if name in _FIELD_VOCABULARY:
            return st.sampled_from(_FIELD_VOCABULARY[name])
        if schema.get("format") == "uuid":
            return st.uuids().map(str)
        if schema.get("format") in {"date-time", "binary"}:
            return st.just(datetime.now(UTC).isoformat())
        floor = int(schema.get("minLength", 0))
        return st.text(
            alphabet=st.characters(min_codepoint=48, max_codepoint=122),
            min_size=floor,
            max_size=max(floor, 12),
        )
    if kind == "integer":
        return st.integers(min_value=0, max_value=1024)
    if kind == "number":
        return st.floats(min_value=0, max_value=1024, allow_nan=False, allow_infinity=False)
    if kind == "boolean":
        return st.booleans()
    return st.none()


def _draw(strategy: st.SearchStrategy[Any], count: int) -> list[Any]:
    """``count`` values from ``strategy``, reproducibly.

    Hypothesis draws inside ``@given``; this borrows that engine for a plain
    corpus, with ``derandomize`` so a red run reproduces and only the generate
    phase so no time goes into shrinking a corpus nobody asserts on.
    """
    drawn: list[Any] = []

    @hypothesis_settings(
        max_examples=count,
        derandomize=True,
        database=None,
        deadline=None,
        phases=[Phase.generate],
        suppress_health_check=list(HealthCheck),
    )
    @given(strategy)
    def collect(value: Any) -> None:
        drawn.append(value)

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        collect()
    return drawn[:count] or [None]


def bodies_for(route: RouteSpec, count: int) -> list[Any]:
    """The JSON bodies to try against ``route``."""
    if route.body_schema is None:
        return [None]
    defs = fastapi_app.openapi().get("components", {}).get("schemas", {})
    return _draw(_strategy(route.body_schema, defs), count)


