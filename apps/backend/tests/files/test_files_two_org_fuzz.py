"""The two-org fuzz: an adversary in org B learns nothing about org A.

Tenant isolation asks for a machine that never gets tired, for *every* route
under the Files prefix and the content mount, requests made by org B's
principals against org A's ids must come back as the one opaque ``404`` with
none of A's bytes in them, never a ``403`` (which would confirm the resource
exists), never a ``5xx`` (which would confirm the id reached code that expected
it to resolve). The no-oracle contract adds the two side channels a body cannot carry: B's
traffic must not move A's quota or ``billable_bytes``, and B exhausting its own
rate limit must not throttle A.

Three properties make this a fuzz rather than a table of hand-picked calls:

* the routes are read from the running app's route table, and the count is
  pinned — a route added without a thought for isolation fails this test before
  it ever fails a review;
* the bodies are generated by Hypothesis from each route's own OpenAPI request
  schema, so a request is schema-valid (it reaches the policy rather than
  bouncing off a ``422``) while still being nobody's idea of a happy path;
* every path parameter is filled with a *real* id of A's — a drive, a folder, a
  file, an object node, a leased folder, a committed version, an open upload
  session, an operation, a share and a content token — so a route that resolves
  an id before it authorizes has something real to resolve and betrays itself.

The generator is derandomized: a failure here reproduces on the next run.
"""

