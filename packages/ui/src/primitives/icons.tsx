// The small inline glyphs the base components need (reveal toggle, field/alert
// status, button spinner). Single-weight, rounded-cap, currentColor, no fill — the
// flask's line language. Kept internal to @alkera/ui; not part of the public
// barrel until there's a real icon API to commit to.

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children"> {
  size?: number;
}

function Svg({ size = 16, className, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className}
      {...rest}
    >
      {children}
    </svg>
  );
}

