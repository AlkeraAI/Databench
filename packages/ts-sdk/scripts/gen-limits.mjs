// Emit the server's own field limits as TypeScript constants.
//
// `openapi-typescript` carries a schema's SHAPE and drops its constraints, so a
// browser that wants to stop a reader before the server refuses them has no
// generated source for the number — and a copy typed into the client is a copy
// that drifts the day the server changes its mind. This reads the same
// committed `openapi.json` the types come from and writes the constraints out
// beside them, so the client's ceiling and the server's ceiling are one fact.
//
// Curated, not exhaustive: each entry is a limit a SURFACE has to show, named
// by the schema and property the server spells it on. A limit nothing renders
// does not belong here.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OPENAPI = fileURLToPath(new URL("../../shared-openapi/openapi.json", import.meta.url));
const OUT = fileURLToPath(new URL("../src/schemaLimits.ts", import.meta.url));

/** The limits the portal renders, each as [exported name, schema, property, keyword, doc]. */
const WANTED = [
  [
    "MAX_CHAT_MESSAGE_CHARS",
    "ChatMessageCreate",
    "text",
    "maxLength",
    "The longest message the chat route accepts, in characters.",
  ],
];

const doc = JSON.parse(readFileSync(OPENAPI, "utf8"));

const lines = [
  "// GENERATED by packages/ts-sdk/scripts/gen-limits.mjs — do not edit.",
  "//",
  "// The constraints the server publishes in its OpenAPI document, which",
  "// `openapi-typescript` does not carry into the generated types. Regenerate",
  "// with `make gen-sdk`.",
  "",
];

for (const [name, schema, property, keyword, description] of WANTED) {
  const value = doc?.components?.schemas?.[schema]?.properties?.[property]?.[keyword];
  if (typeof value !== "number") {
    throw new Error(
      `openapi.json has no ${keyword} for ${schema}.${property} — the server stopped publishing a limit this client renders`,
    );
  }
  lines.push(`/** ${description} */`);
  lines.push(`export const ${name} = ${value};`);
  lines.push("");
}

writeFileSync(OUT, lines.join("\n"), "utf8");
process.stdout.write(`wrote ${OUT}\n`);
