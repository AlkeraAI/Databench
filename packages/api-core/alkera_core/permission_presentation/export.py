"""The registry and the conformance vectors, as the files the TS twin reads.

``scripts/export_permission_presentation.py`` writes what these return; the
drift gate (and
``packages/api-core/tests/permission_presentation/test_permission_export.py``)
fails when a committed copy no longer matches, so the web can never run on a registry the
server has moved past.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Any

from alkera_core.permission_presentation.model import PRESENTATION_VERSION, PermissionAsk
from alkera_core.permission_presentation.modes import PERMISSION_MODES
from alkera_core.permission_presentation.outcome import outcome_document
from alkera_core.permission_presentation.present import present
from alkera_core.permission_presentation.registry import (
    DECISION_OUTCOMES,
    EFFECT_REASONS,
    EXACT_ALWAYS_LABEL,
    EXEC_TITLE,
    NATIVE_TOOL_ALIASES,
    NATIVE_TOOL_NAMES,
    NOTEBOOK_PREVIEW_LINES,
    NOTEBOOK_PREVIEW_WIDTH,
    OPERATION_REASONS,
    REDACTED,
    REDACTION_RULES,
    SENSITIVE_INPUT_KEY_PATTERN,
    SUBJECT_INPUT_KEYS,
    UNSURE_REASON,
    presenters,
)
from alkera_core.permission_presentation.vectors import VECTORS

REPO_ROOT = Path(__file__).resolve().parents[4]
TS_REGISTRY_PATH = REPO_ROOT / "packages/chat-model/src/generated/permissionPresentation.ts"
VECTORS_PATH = REPO_ROOT / "packages/chat-model/src/generated/permissionPresentationVectors.json"
ALKERA_TOOLS_PATH = Path(__file__).resolve().parent / "_alkera_tools.py"
TOOL_MANIFEST_PATH = REPO_ROOT / "packages/shared-openapi/tool-manifest.json"


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def _camel_keys(value: Any) -> Any:
    if isinstance(value, dict):
        return {_camel(str(k)): _camel_keys(v) for k, v in value.items()}
    if isinstance(value, list | tuple):
        return [_camel_keys(v) for v in value]
    return value


def registry_document() -> dict[str, Any]:
    """Everything the TS twin needs to present an ask the way this package does."""
    return {
        "version": PRESENTATION_VERSION,
        "execTitle": EXEC_TITLE,
        "exactAlwaysLabel": EXACT_ALWAYS_LABEL,
        "decisionOutcomes": dict(DECISION_OUTCOMES),
        "effectReasons": dict(EFFECT_REASONS),
        "operationReasons": dict(OPERATION_REASONS),
        "unsureReason": UNSURE_REASON,
        "notebookPreviewLines": NOTEBOOK_PREVIEW_LINES,
        "notebookPreviewWidth": NOTEBOOK_PREVIEW_WIDTH,
        "subjectInputKeys": list(SUBJECT_INPUT_KEYS),
        "redacted": REDACTED,
        "redactionRules": [_camel_keys(asdict(rule)) for rule in REDACTION_RULES],
        "secretKeyPattern": SENSITIVE_INPUT_KEY_PATTERN,
        "nativeToolAliases": dict(NATIVE_TOOL_ALIASES),
        "presenters": [
            {
                **_camel_keys({k: v for k, v in asdict(p).items() if k != "scope_phrases"}),
                "scopePhrases": dict(p.scope_phrases),
            }
            for p in presenters()
        ],
        "modes": [_camel_keys(asdict(mode)) for mode in PERMISSION_MODES],
        "outcomes": outcome_document(),
    }


def vector_document() -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for name, raw in VECTORS.items():
        ask = PermissionAsk.model_validate(raw)
        out.append(
            {
                "name": name,
                "ask": ask.to_json(),
                "presentation": present(ask).to_json(),
            }
        )
    return out


def render_ts() -> str:
    registry = json.dumps(registry_document(), indent=2, ensure_ascii=False)
    natives = json.dumps(list(NATIVE_TOOL_NAMES), indent=2)
    return (
        "/* eslint-disable */\n"
        "/**\n"
        " * Auto-generated from alkera_core.permission_presentation (the registry,\n"
        " * the redaction rules and the permission modes). Do not edit by hand:\n"
        " * change the Python registry and run `make gen-tool-manifest`.\n"
        " */\n\n"
        f"export const NATIVE_TOOL_NAMES = {natives} as const;\n\n"
        f"export const PERMISSION_PRESENTATION_REGISTRY = {registry} as const;\n"
    )


def render_vectors() -> str:
    return json.dumps(vector_document(), indent=2, ensure_ascii=False) + "\n"


def render_alkera_tools(manifest_path: Path = TOOL_MANIFEST_PATH) -> str:
    names = sorted(json.loads(manifest_path.read_text())["x-alkera-tools"])
    body = "".join(f'    "{name}",\n' for name in names)
    return (
        '"""Every alkera tool name, from ``packages/shared-openapi/tool-manifest.json``.\n\n'
        "Generated by ``scripts/export_permission_presentation.py``; do not edit.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        f"ALKERA_TOOL_NAMES: tuple[str, ...] = (\n{body})\n"
    )


def outputs() -> dict[Path, str]:
    """Every generated file and what it must contain."""
    return {
        ALKERA_TOOLS_PATH: render_alkera_tools(),
        TS_REGISTRY_PATH: render_ts(),
        VECTORS_PATH: render_vectors(),
    }


def write(path: Path, content: str) -> None:
    """Write a generated file with LF endings on every platform: Windows would
    otherwise translate each newline to CRLF and the committed bytes would
    depend on the machine that generated them."""
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)


def is_current(path: Path, content: str) -> bool:
    """Whether the file on disk says what ``content`` says. Line endings are
    not content: a Windows checkout (``core.autocrlf=true``) holds the committed
    LF file as CRLF, and that is the same file."""
    on_disk = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    return on_disk == content


