"""The Alkera Files library.

Files is library-first: the storage tree, the content plane, uploads, leases,
access decisions and the sweepers all live here as plain Python, and the HTTP
routes, the CLI verbs and the worker jobs are thin facades over them. Nothing
in this package imports a route, a CLI command or a worker; it depends only on
the shared building blocks in ``alkera_core`` (``authz``, ``events``,
``config``, ``versioning``, ``db``, ``models``).

Every top-level module re-exports its public seams here, so callers import the
package rather than its modules. ``store/``, ``sync/`` and ``authz/`` are
subpackages with their own barrels and are imported by path; the request and
response shapes live in ``alkera_core.schemas.files``, which is its own barrel.

No public name is bound twice. A flat barrel can hold one meaning per name, so
a constant two modules both wanted is spelled for the module that owns it —
``ACL_REWRITE_BATCH`` and ``STATS_FOLD_BATCH``, ``LEASE_TTL`` and
``content_url_ttl``, ``IDEMPOTENCY_RETENTION`` and ``DELTA_RETENTION``,
``DELTA_MAX_LIMIT`` beside the listing's ``MAX_LIMIT`` — rather than resolved by
picking a winner here and leaving the loser reachable only by path. Where two
modules really do offer the same object (``conflicts`` re-exports ``names``'
``NAME_MAX_BYTES``) the barrel binds it once; ``acl_intern.intern`` is the one
lower-level variant that stays a module-path import, since ``intern`` on the
package means the ACL module's.
"""

