def _check_param(value: object, path: str, walk: _Walk) -> object:
    raw = _mapping(value, path)
    name = raw.get("name")
    if not isinstance(name, str) or not re.match(PARAM_NAME, name):
        raise ChartSpecError(
            f"{_join(path, 'name')} must be a name of letters, digits and _", _join(path, "name")
        )
    if name in RESERVED_PARAM_NAMES:
        raise ChartSpecError(
            f"{_join(path, 'name')} is reserved by the renderer", _join(path, "name")
        )
    if name in walk.params:
        raise ChartSpecError(f"{_join(path, 'name')} repeats a selection name", _join(path, "name"))
    select = Obj(
        {
            "type": Enum({"interval", "point"}),
            "encodings": Arr(Registry(lambda p: p.channels, "channel"), max_items=4),
            "fields": Arr(Field(), max_items=8),
            "nearest": Bool(),
            "toggle": Bool(),
            "clear": Bool(),
            "resolve": Enum({"global", "union", "intersect"}),
            "mark": Obj(
                {
                    "fill": Color(),
                    "fillOpacity": OPACITY,
                    "stroke": Color(),
                    "strokeOpacity": OPACITY,
                    "strokeWidth": Num(0, 50),
                    "strokeDash": STROKE_DASH,
                },
                what="brush style",
            ),
        },
        required=("type",),
        what="selection",
    )
    rule = Obj(
        {
            "name": Str(64),
            "select": OneOf(Enum({"interval", "point"}), select),
            # Only the two bindings that are interactions inside the chart:
            # zoom and pan ("scales") and a clickable legend. An input-element
            # binding is a widget, a later seam.
            "bind": Enum({"scales", "legend"}),
            "views": Arr(Str(64, PARAM_NAME), max_items=MAX_VIEWS),
        },
        required=("name", "select"),
        what="selection parameter",
    )
    admitted = rule.check(raw, path, walk)
    walk.params[name] = path
    return admitted


