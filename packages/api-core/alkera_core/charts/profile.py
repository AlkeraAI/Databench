def _as_list(value: object) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        return [item for item in value if isinstance(item, str)]
    return []


def _outputs_of(entries_key: str) -> Callable[[Mapping[str, Any]], Iterable[str]]:
    def outputs(t: Mapping[str, Any]) -> Iterable[str]:
        return [
            e["as"]
            for e in t.get(entries_key, [])
            if isinstance(e, Mapping) and isinstance(e.get("as"), str)
        ]

    return outputs


