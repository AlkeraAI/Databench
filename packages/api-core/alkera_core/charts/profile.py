def _scan_number(text: str, i: int) -> tuple[int, float]:
    n = len(text)
    if text.startswith(("0x", "0X"), i):
        j = i + 2
        while j < n and text[j] in _HEX_DIGITS:
            j += 1
        if j == i + 2:
            raise ExpressionError(_MALFORMED)
        value = float(int(text[i + 2 : j], 16))
    else:
        j = i
        while j < n and text[j] in _DIGITS:
            j += 1
        if j - i > 1 and text[i] == "0":
            # Vega reads a leading zero as an octal literal; nothing writes one.
            raise ExpressionError("writes a number with a leading zero")
        if j < n and text[j] == ".":
            j += 1
            while j < n and text[j] in _DIGITS:
                j += 1
        if j < n and text[j] in "eE":
            k = j + 1
            if k < n and text[k] in "+-":
                k += 1
            if k >= n or text[k] not in _DIGITS:
                raise ExpressionError(_MALFORMED)
            while k < n and text[k] in _DIGITS:
                k += 1
            j = k
        value = float(text[i:j])
    if j < n and text[j] in _ID_PART:
        raise ExpressionError(_MALFORMED)
    return j, value


def _scan_hex(text: str, i: int, count: int) -> int:
    digits = text[i : i + count]
    if len(digits) != count or any(ch not in _HEX_DIGITS for ch in digits):
        raise ExpressionError(_MALFORMED)
    return int(digits, 16)


def _scan_string(text: str, i: int) -> tuple[int, str]:
    quote = text[i]
    n = len(text)
    out: list[str] = []
    j = i + 1
    while True:
        if j >= n:
            raise ExpressionError(_MALFORMED)
        ch = text[j]
        if ch == quote:
            return j + 1, "".join(out)
        if ch in _LINE_BREAKS:
            raise ExpressionError(_MALFORMED)
        if ch != "\\":
            out.append(ch)
            j += 1
            continue
        j += 1
        if j >= n:
            raise ExpressionError(_MALFORMED)
        esc = text[j]
        if esc in _SIMPLE_ESCAPES:
            out.append(_SIMPLE_ESCAPES[esc])
            j += 1
        elif esc == "0" and not (j + 1 < n and text[j + 1] in _DIGITS):
            out.append("\0")
            j += 1
        elif esc == "x":
            out.append(chr(_scan_hex(text, j + 1, 2)))
            j += 3
        elif esc == "u" and j + 1 < n and text[j + 1] == "{":
            end = text.find("}", j + 2)
            digits = text[j + 2 : end] if end != -1 else ""
            if not 1 <= len(digits) <= 6 or any(c not in _HEX_DIGITS for c in digits):
                raise ExpressionError(_MALFORMED)
            code = int(digits, 16)
            if code > 0x10FFFF:
                raise ExpressionError(_MALFORMED)
            out.append(chr(code))
            j = end + 1
        elif esc == "u":
            out.append(chr(_scan_hex(text, j + 1, 4)))
            j += 5
        else:
            # Every other escape (octal, a line continuation, an identity
            # escape) is refused rather than decoded one way here and another
            # in the renderer.
            raise ExpressionError(_MALFORMED)


def _tokenize(text: str) -> list[_Token]:
    tokens: list[_Token] = []
    n = len(text)
    i = 0
    while i < n:
        ch = text[i]
        if ch in _EXPRESSION_SPACE:
            i += 1
        elif ch in _ID_START:
            j = i + 1
            while j < n and text[j] in _ID_PART:
                j += 1
            tokens.append(("id", text[i:j]))
            i = j
        elif ch in _DIGITS or (ch == "." and i + 1 < n and text[i + 1] in _DIGITS):
            i, number = _scan_number(text, i)
            tokens.append(("num", number))
        elif ch in "'\"":
            i, value = _scan_string(text, i)
            tokens.append(("str", value))
        else:
            for punctuator in _PUNCTUATORS:
                if text.startswith(punctuator, i):
                    tokens.append(("punc", punctuator))
                    i += len(punctuator)
                    break
            else:
                raise ExpressionError(_MALFORMED)
    tokens.append(("end", None))
    return tokens


class _ExpressionParser:
    """Recursive descent over vega-expression's grammar, to a tuple tree:
    ``("num", v)``, ``("str", v)``, ``("lit", v)``, ``("id", name)``,
    ``("member", object, property, computed)``, ``("call", name, args)``,
    ``("array", items)``, ``("unary", op, arg)``, ``("binary", op, l, r)``,
    ``("cond", test, yes, no)``."""

    def __init__(self, tokens: list[_Token]) -> None:
        self.tokens = tokens
        self.pos = 0
        self.depth = 0

    def _at(self, punctuator: str) -> bool:
        kind, value = self.tokens[self.pos]
        return kind == "punc" and value == punctuator

    def _expect(self, punctuator: str) -> None:
        if not self._at(punctuator):
            raise ExpressionError(_MALFORMED)
        self.pos += 1

    def _enter(self) -> None:
        self.depth += 1
        if self.depth > MAX_EXPRESSION_DEPTH:
            raise ExpressionError(f"nests deeper than {MAX_EXPRESSION_DEPTH} levels")

    def parse(self) -> _Node:
        node = self._conditional()
        if self.tokens[self.pos][0] != "end":
            raise ExpressionError(_MALFORMED)
        return node

    def _conditional(self) -> _Node:
        self._enter()
        node = self._binary(1)
        if self._at("?"):
            self.pos += 1
            yes = self._conditional()
            self._expect(":")
            no = self._conditional()
            node = ("cond", node, yes, no)
        self.depth -= 1
        return node

    def _binary(self, min_precedence: int) -> _Node:
        left = self._unary()
        while True:
            kind, value = self.tokens[self.pos]
            precedence = _BINARY_PRECEDENCE.get(value) if kind == "punc" else None
            if precedence is None or precedence < min_precedence:
                return left
            self.pos += 1
            right = self._binary(precedence + 1)
            left = ("binary", value, left, right)

    def _unary(self) -> _Node:
        kind, value = self.tokens[self.pos]
        if kind == "punc" and value in _UNARY_OPERATORS:
            self.pos += 1
            self._enter()
            argument = self._unary()
            self.depth -= 1
            return ("unary", value, argument)
        return self._postfix()

    def _list(self, close: str) -> list[_Node]:
        items: list[_Node] = []
        if self._at(close):
            self.pos += 1
            return items
        while True:
            items.append(self._conditional())
            if self._at(","):
                self.pos += 1
                continue
            self._expect(close)
            return items

    def _postfix(self) -> _Node:
        node = self._primary()
        while True:
            if self._at("."):
                self.pos += 1
                kind, value = self.tokens[self.pos]
                if kind != "id":
                    raise ExpressionError(_MALFORMED)
                self.pos += 1
                node = ("member", node, ("str", value), False)
            elif self._at("["):
                self.pos += 1
                prop = self._conditional()
                self._expect("]")
                node = ("member", node, prop, True)
            elif self._at("("):
                if node[0] != "id":
                    raise ExpressionError("calls something that is not a function name")
                self.pos += 1
                args = self._list(")")
                if len(args) > MAX_EXPRESSION_ARGS:
                    raise ExpressionError(
                        f"passes more than {MAX_EXPRESSION_ARGS} arguments to a function"
                    )
                node = ("call", node[1], args)
            else:
                return node

    def _primary(self) -> _Node:
        kind, value = self.tokens[self.pos]
        self.pos += 1
        if kind in ("num", "str"):
            return (kind, value)
        if kind == "id":
            if value in ("true", "false"):
                return ("lit", value == "true")
            if value == "null":
                return ("lit", None)
            return ("id", value)
        if kind == "punc" and value == "(":
            node = self._conditional()
            self._expect(")")
            return node
        if kind == "punc" and value == "[":
            items = self._list("]")
            if len(items) > MAX_LIST:
                raise ExpressionError(f"writes an array of more than {MAX_LIST} items")
            return ("array", items)
        raise ExpressionError(_MALFORMED)


def _is_index(node: _Node) -> bool:
    return node[0] == "num" and node[1] >= 0 and float(node[1]).is_integer()


def _check_expression_tree(root: _Node, profile: Profile) -> list[str]:
    fields: list[str] = []
    stack = [root]
    while stack:
        node = stack.pop()
        kind = node[0]
        if kind in ("num", "lit"):
            continue
        if kind == "str":
            if node[1] in EXPRESSION_FORBIDDEN_NAMES:
                raise ExpressionError("names a property no expression may read")
        elif kind == "id":
            if node[1] == "datum":
                raise ExpressionError("reads the whole row; read one field by name")
            if node[1] not in profile.expression_constants:
                raise ExpressionError("reads a name outside the expression allowlist")
        elif kind == "member":
            _, obj, prop, computed = node
            if obj == ("id", "datum"):
                if prop[0] != "str":
                    raise ExpressionError("reads a row field by a computed key; name it")
                if not prop[1] or prop[1] in EXPRESSION_FORBIDDEN_NAMES:
                    raise ExpressionError("names a property no expression may read")
                fields.append(prop[1])
            elif computed and _is_index(prop):
                stack.append(obj)
            else:
                raise ExpressionError("reads a property of something other than the row")
        elif kind == "call":
            _, name, args = node
            if name not in profile.expression_functions:
                raise ExpressionError("calls a function outside the expression allowlist")
            arity = _EXACT_ARITY.get(name)
            if arity is not None and len(args) != arity:
                raise ExpressionError(f"calls a function that takes {arity} arguments")
            if name == "pad" and not (
                len(args) >= 2 and _is_index(args[1]) and args[1][1] <= MAX_PAD_LENGTH
            ):
                raise ExpressionError(
                    f"pads to a length that is not a number of at most {MAX_PAD_LENGTH}"
                )
            stack.extend(args)
        elif kind == "array":
            stack.extend(node[1])
        elif kind == "unary":
            stack.append(node[2])
        elif kind == "binary":
            stack.extend((node[2], node[3]))
        else:
            stack.extend(node[1:])
    return fields


def check_expression(text: str, profile: Profile | None = None) -> list[str]:
    """The row fields ``text`` reads (sorted, each once), or
    :class:`ExpressionError` naming why it is outside the profile."""
    if not isinstance(text, str):
        raise ExpressionError("must be an expression string")
    # Measured in UTF-16 code units, as the renderer measures it.
    if len(text.encode("utf-16-le")) // 2 > MAX_EXPRESSION_CHARS:
        raise ExpressionError(f"is longer than {MAX_EXPRESSION_CHARS} characters")
    tokens = _tokenize(text)
    if len(tokens) == 1:
        raise ExpressionError("is empty")
    tree = _ExpressionParser(tokens).parse()
    return sorted(set(_check_expression_tree(tree, profile or PROFILE)))


class Expression(Rule):
    """A Vega expression string inside the profile's grammar and allowlist.
    The row fields it reads are recorded for binding, like any other field."""

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if not isinstance(value, str):
            raise ChartSpecError(f"{_label(path)} must be an expression string", path)
        try:
            fields = check_expression(value, walk.profile)
        except ExpressionError as exc:
            raise ChartSpecError(f"{_label(path)} {exc}", path) from None
        walk.fields.extend((path, escape_field(name)) for name in fields)
        return value

    def describe(self) -> str:
        return "expression"


