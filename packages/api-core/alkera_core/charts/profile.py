"""The Alkera chart profile: a strict, validated subset of Vega-Lite v6.

A chart is a declarative spec, data plus encodings, and the rows it describes
are often the customer's stored LLM output: maximally adversarial text that an
agent read before it wrote the spec. So the validator is an **allowlist
walker**, never a denylist. Every key at every level is admitted because a rule
here names it; an unknown key is a refusal, which is why a Vega-Lite feature we
never considered (``data.url``, an ``expr`` anywhere, a ``bind`` to an input
element, a ``labelExpr``) cannot arrive by being forgotten.

What the profile guarantees about an admitted spec:

* **Nothing in it fetches.** No ``url`` anywhere, no image mark, no ``href``
  channel, no ``$schema`` other than the Vega-Lite URLs the renderer ignores.
* **Its expressions read rows and nothing else.** A ``calculate``, a string
  ``filter`` and a condition's string ``test`` are parsed with vega-expression's
  grammar and admitted only when every name in them is a field of ``datum``, a
  constant or one of Vega's pure functions (see *Expressions* below). No
  ``expr`` or ``signal`` key, no ``labelExpr``. Colors match a CSS color
  grammar, formats are bounded pattern strings. The renderer still runs Vega
  with ``vega-interpreter`` and a loader that refuses every load; the profile
  is the first wall, not the only one.
* **It is bounded.** Rows, columns, cell sizes, views, layers and transforms
  all have ceilings, so a spec cannot be made expensive to validate or render.
* **It binds.** Every field an encoding, a transform or a predicate names is
  reported with its path, so a caller holding the data's columns can refuse a
  typo instead of drawing an empty figure (Vega-Lite drops it silently).

The profile is **extended by registration**: marks, encoding channels,
transforms, aggregate ops, time units and color schemes live in registries on
a :class:`Profile`, and :data:`PROFILE` is the default one. A v1 feature is a
``register_*`` call, never a new branch in the walker.

This module is deliberately self-contained: standard library only, Python 3.8
syntax and runtime (the ``alkera`` distribution's floor). That distribution ships a
byte-identical copy (``packages/alkera-py/alkera/chart/_profile.py``, regenerated by ``make
gen-chart-profile``) so a notebook validates exactly as the server does without
importing anything from Alkera's own environment.

Error messages name the offending **path** and the allowed vocabulary, never a
value: a value is the customer's data or column name, and an echoed value is
the injected string handed back.
"""

