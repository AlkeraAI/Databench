# Expressions -----------------------------------------------------------------
#
# Vega-Lite reads a string as an expression in places Altair writes every day:
# a ``calculate`` transform, a ``filter`` written as text (``transform_filter``
# with a string or an ``alt.datum`` comparison) and a condition's ``test``
# (``alt.condition`` and ``alt.when`` over ``alt.datum``). The renderer runs them
# with ``vega-interpreter`` over a parsed AST, never ``eval``, and its loader
# refuses every load, so an expression cannot fetch or generate code. What is
# left is what an expression may *read*, and that is decided here: a real
# tokenizer and parser for the grammar vega-expression accepts, then an
# allowlist over the tree. Admitted: literals (numbers, strings, booleans,
# null, arrays), fields of ``datum`` by name or by string key, the unary,
# binary, logical and ternary operators, Vega's constants, and Vega's pure
# functions. Refused: every other identifier (Vega would resolve it as a
# signal), member access on anything but ``datum`` (a numeric index into a
# value is the one exception), calls on anything but a function name, object
# and regular-expression literals, assignment, and any property name that
# reaches a prototype, in any spelling an escape can produce.
#
# ``now``, ``random`` and the ``sample*`` draws are admitted although they are
# not deterministic: they read the clock or a random source and nothing else,
# and Altair's jitter and "days since" recipes need them. Refused on purpose:
# ``regexp`` and ``test`` (a pattern can backtrack catastrophically on a
# customer's text), ``sequence``, ``timeSequence`` and ``utcSequence`` (they
# allocate without bound), ``merge`` and ``pluck`` (object assembly and field
# accessors), the data, scale, event, geo and tree functions (they reach the
# runtime's state), and the logging functions. ``pad`` allocates its length,
# so its length must be a number literal of at most ``MAX_PAD_LENGTH``.
#
# The renderer's guard (``packages/chart-guard/src/expression.ts``) implements the
# same grammar and the same allowlist; the shared corpus under
# ``packages/api-core/tests/fixtures/charts/profile/expressions`` holds both to
# it.

