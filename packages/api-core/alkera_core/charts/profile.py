def _check_view(value: object, path: str, walk: _Walk, *, in_layer: bool = False) -> object:
    raw = _mapping(value, path)
    walk.views += 1
    if walk.views > MAX_VIEWS:
        raise ChartSpecError(f"{_label(path)} brings the chart past {MAX_VIEWS} views", path)
    kinds = [key for key in ("mark", *COMPOSITIONS) if key in raw]
    if len(kinds) != 1:
        raise ChartSpecError(
            f"{_label(path)} must have exactly one of mark, layer, hconcat, vconcat, "
            "concat or facet",
            path,
        )
    kind = kinds[0]
    if in_layer and kind not in ("mark", "layer"):
        raise ChartSpecError(f"{_label(path)} must be a mark or a layer view", path)
    walk.depth += 1
    if walk.depth > MAX_NESTING:
        raise ChartSpecError(f"{_label(path)} nests compositions deeper than {MAX_NESTING}", path)
    try:
        fields = dict(VIEW_COMMON)
        child = Custom(lambda v, p, w: _check_view(v, p, w), "view", {"object"})
        if kind == "mark":
            fields.update({"mark": MARK, "encoding": ENCODING, "params": PARAMS})
        elif kind == "layer":
            layer_child = Custom(
                lambda v, p, w: _check_view(v, p, w, in_layer=True), "layer view", {"object"}
            )
            fields.update(
                {
                    "layer": Arr(layer_child, min_items=1, max_items=MAX_LAYERS),
                    "encoding": ENCODING,
                    "resolve": RESOLVE,
                }
            )
        elif kind == "facet":
            facet_child = Custom(
                lambda v, p, w: _check_view(v, p, w, in_layer=True), "faceted view", {"object"}
            )
            fields.update(
                {
                    "facet": OneOf(
                        Obj(
                            {
                                "row": _channel(FACET, conditional=False),
                                "column": _channel(FACET, conditional=False),
                            },
                            what="row/column facet",
                        ),
                        _channel(FACET, conditional=False),
                    ),
                    "spec": facet_child,
                    "columns": Num(1, 64, integer=True),
                    "resolve": RESOLVE,
                    "spacing": PIXELS,
                }
            )
            if "spec" not in raw:
                raise ChartSpecError(
                    f"{_label(path)} must name spec for its facet", _join(path, "spec")
                )
        else:
            fields.update(
                {
                    kind: Arr(child, min_items=1, max_items=MAX_VIEWS),
                    "resolve": RESOLVE,
                    "spacing": PIXELS,
                }
            )
            if kind == "concat":
                fields["columns"] = Num(1, 64, integer=True)
        if path == "":
            fields.update(TOP_LEVEL)
        if not walk.policy.inline:
            # A bound chart's rows are its result's; a data block is simply
            # not part of its vocabulary.
            fields.pop("data", None)
            fields.pop("datasets", None)
        return Obj(fields, what="view").check(raw, path, walk)
    finally:
        walk.depth -= 1


