def _aggregate_op() -> Rule:
    return OneOf(
        Registry(lambda p: p.aggregates, "aggregate op"),
        Obj({"argmin": Field()}, required=("argmin",), what="{argmin: field}"),
        Obj({"argmax": Field()}, required=("argmax",), what="{argmax: field}"),
    )


