def _check_transform(value: object, path: str, walk: _Walk) -> object:
    raw = _mapping(value, path)
    transforms = walk.profile.transforms
    keys = [key for key in raw if key in transforms]
    if len(keys) != 1:
        raise ChartSpecError(
            f"{_label(path)} must be exactly one of the transforms {sorted(transforms)}", path
        )
    registered = transforms[keys[0]]
    admitted = registered.rule.check(raw, path, walk)
    outputs = registered.outputs(raw)
    if outputs is None:
        walk.opaque_outputs = True
    else:
        walk.produced.update(name for name in outputs if isinstance(name, str) and name)
    return admitted


