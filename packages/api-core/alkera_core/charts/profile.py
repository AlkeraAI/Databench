def _check_rows(value: object, path: str, walk: _Walk) -> object:
    if not isinstance(value, list):
        raise ChartSpecError(f"{_label(path)} must be a list of row objects", path)
    walk.rows += len(value)
    if walk.rows > MAX_INLINE_ROWS:
        raise ChartSpecError(
            f"{_label(path)} brings the chart past {MAX_INLINE_ROWS} inline rows; "
            "aggregate first, or sample (alkera.chart samples for you)",
            path,
        )
    for i, row in enumerate(value):
        row_path = _index(path, i)
        if not isinstance(row, Mapping):
            raise ChartSpecError(f"{_label(row_path)} must be an object of field values", row_path)
        if len(row) > MAX_ROW_FIELDS:
            raise ChartSpecError(
                f"{_label(row_path)} has more than {MAX_ROW_FIELDS} fields", row_path
            )
        for key, cell in row.items():
            if not isinstance(key, str) or len(key) > MAX_FIELD_CHARS:
                raise ChartSpecError(
                    f"{_label(row_path)} has a field name that is not a string of at most "
                    f"{MAX_FIELD_CHARS} characters",
                    row_path,
                )
            walk.columns.add(key)
            if cell is None or isinstance(cell, bool):
                continue
            if isinstance(cell, (int, float)):
                if isinstance(cell, float) and not math.isfinite(cell):
                    raise ChartSpecError(
                        f"{_label(row_path)} holds a number that is not finite (use null)", row_path
                    )
                continue
            if isinstance(cell, str):
                if len(cell) > MAX_CELL_CHARS:
                    raise ChartSpecError(
                        f"{_label(row_path)} holds a value longer than {MAX_CELL_CHARS} characters",
                        row_path,
                    )
                continue
            raise ChartSpecError(
                f"{_label(row_path)} holds a value that is not a string, number, boolean or null",
                row_path,
            )
    return [dict(row) for row in value]


ROWS = Custom(_check_rows, "row list", {"array"})


#: Delimited-text formats. Vega parses them by compiling a row function with
#: ``new Function``, which the renderer's content security policy blocks.
_DELIMITED_FORMATS = frozenset({"csv", "tsv", "dsv"})
_DELIMITED_SUFFIXES = (".csv", ".tsv")


def _refuse_delimited(raw: Mapping[str, Any], path: str) -> None:
    fmt = raw.get("format")
    url = raw.get("url")
    delimited = (
        (isinstance(fmt, Mapping) and str(fmt.get("type", "")).lower() in _DELIMITED_FORMATS)
        or isinstance(raw.get("values"), str)
        or (
            isinstance(url, str)
            and url.split("?", 1)[0].split("#", 1)[0].lower().endswith(_DELIMITED_SUFFIXES)
        )
    )
    if delimited:
        raise ChartSpecError(
            f"{_label(path)} holds CSV or TSV text, which charts do not parse; give the "
            "rows inline as a list of objects (alkera.chart reads CSV for you)",
            path,
        )


def _check_data(value: object, path: str, walk: _Walk) -> object:
    policy = walk.policy
    raw = _mapping(value, path)
    if not policy.inline:
        raise ChartSpecError(
            f"{_label(path)} is not admitted: this chart's rows come from its result", path
        )
    _refuse_delimited(raw, path)
    if "values" in raw:
        return Obj(
            {"values": ROWS, "name": Str(64)}, required=("values",), what="inline data"
        ).check(raw, path, walk)
    rule = Obj({"name": Str(128, r"^[A-Za-z0-9_.:-]+$")}, required=("name",), what="named data")
    admitted = rule.check(raw, path, walk)
    walk.data_refs.append((_join(path, "name"), raw["name"]))
    return admitted


DATA = Custom(_check_data, "data", {"object"})


def _check_datasets(value: object, path: str, walk: _Walk) -> object:
    raw = _mapping(value, path)
    if not walk.policy.inline:
        raise ChartSpecError(
            f"{_label(path)} is not admitted: this chart's rows come from its result", path
        )
    if len(raw) > MAX_DATASETS:
        raise ChartSpecError(f"{_label(path)} holds more than {MAX_DATASETS} datasets", path)
    out: dict[str, object] = {}
    for name, rows in raw.items():
        Str(128, r"^[A-Za-z0-9_.:-]+$").check(name, path, walk)
        walk.dataset_names.add(name)
        if isinstance(rows, str):
            _refuse_delimited({"values": rows}, _join(path, name))
        out[name] = ROWS.check(rows, _join(path, name), walk)
    return out


