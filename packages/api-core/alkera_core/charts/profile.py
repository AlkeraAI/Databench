class ChartSpecError(ValueError):
    """A spec fell outside the profile.

    ``path`` is where (``layer[1].encoding.x.field``), empty for the spec
    itself; the message names the path and the allowed vocabulary, never a
    value.
    """

    def __init__(self, message: str, path: str = "") -> None:
        super().__init__(message)
        self.path = path


def _label(path: str) -> str:
    return path or "a chart spec"


def _join(path: str, key: str) -> str:
    return f"{path}.{key}" if path else key


def _index(path: str, i: int) -> str:
    return f"{path}[{i}]"


class DataPolicy:
    """Where a spec's rows may come from.

    * ``inline``: ``data.values`` and named ``datasets`` carried in the spec.
    * ``host_tables``: ``data: {"name": ...}`` naming a table the host supplies
      (a result's rows, an Arrow attachment) rather than a dataset in the spec.
    * ``bound``: no data block at all; the host binds its one table (a saved
      result's rows) to the spec.
    """

    __slots__ = ("bound", "host_tables", "inline", "name")

    def __init__(self, name: str, *, inline: bool, host_tables: bool, bound: bool) -> None:
        self.name = name
        self.inline = inline
        self.host_tables = host_tables
        self.bound = bound

    def __repr__(self) -> str:
        return f"DataPolicy({self.name!r})"


#: A saved result's chart: the spec names columns, the result supplies rows.
BOUND = DataPolicy("bound", inline=False, host_tables=False, bound=True)
#: A notebook output, an agent's chart, an export: the rows travel in the spec.
INLINE = DataPolicy("inline", inline=True, host_tables=False, bound=True)
#: Inline rows plus named tables the host resolves (Arrow attachments, results).
HOSTED = DataPolicy("hosted", inline=True, host_tables=True, bound=True)


class _Walk:
    """What one validation pass learns on its way through a spec."""

    def __init__(self, profile: Profile, policy: DataPolicy) -> None:
        self.profile = profile
        self.policy = policy
        self.rows = 0
        self.views = 0
        self.depth = 0
        self.fields: list[tuple[str, str]] = []
        self.produced: set[str] = set()
        self.opaque_outputs = False
        self.params: dict[str, str] = {}
        self.param_refs: list[tuple[str, str]] = []
        self.dataset_names: set[str] = set()
        self.data_refs: list[tuple[str, str]] = []
        self.columns: set[str] = set()
        self.marks: set[str] = set()


# --------------------------------------------------------------------------
# Rules: each checks one value at one path and returns the admitted value.
# --------------------------------------------------------------------------


class Rule:
    """One allowlisted value shape. ``describe`` is what an author is told."""

    def check(self, value: object, path: str, walk: _Walk) -> object:
        raise NotImplementedError

    def describe(self) -> str:
        raise NotImplementedError


class Str(Rule):
    def __init__(
        self, max_chars: int = MAX_TEXT_CHARS, pattern: str | None = None, what: str = "string"
    ) -> None:
        self.max_chars = max_chars
        self.pattern = re.compile(pattern) if pattern else None
        self.what = what

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if not isinstance(value, str):
            raise ChartSpecError(f"{_label(path)} must be a string", path)
        if len(value) > self.max_chars:
            raise ChartSpecError(
                f"{_label(path)} must be at most {self.max_chars} characters", path
            )
        if self.pattern is not None and not self.pattern.match(value):
            raise ChartSpecError(f"{_label(path)} is not an admitted {self.describe()}", path)
        return value

    def describe(self) -> str:
        return self.what


class Format(Str):
    """A d3-format or d3-time-format pattern: printable, no braces, bounded."""

    def __init__(self) -> None:
        super().__init__(64, r"^[^{}<>\\\x00-\x1f]*$")

    def describe(self) -> str:
        return "format pattern"


class Color(Str):
    """A CSS color literal: hex, a named color, or ``rgb()``/``hsl()`` with
    numeric arguments. Never ``url(...)``: an SVG paint server is a fetch."""

    def __init__(self) -> None:
        super().__init__(
            48,
            r"^(#[0-9a-fA-F]{3,8}|[a-zA-Z]{3,24}|"
            r"(rgb|rgba|hsl|hsla)\(\s*[0-9.%\s,/+-]{1,40}\))$",
        )

    def describe(self) -> str:
        return "color (hex, a named color, rgb() or hsl())"


class Num(Rule):
    def __init__(self, lo: float = -1e15, hi: float = 1e15, *, integer: bool = False) -> None:
        self.lo = lo
        self.hi = hi
        self.integer = integer

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ChartSpecError(f"{_label(path)} must be a {self.describe()}", path)
        if self.integer and not isinstance(value, int):
            raise ChartSpecError(f"{_label(path)} must be an integer", path)
        if isinstance(value, float) and not math.isfinite(value):
            raise ChartSpecError(f"{_label(path)} must be a finite number", path)
        if not self.lo <= value <= self.hi:
            raise ChartSpecError(
                f"{_label(path)} must be between {_num(self.lo)} and {_num(self.hi)}", path
            )
        return value

    def describe(self) -> str:
        return "integer" if self.integer else "number"


def _num(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else str(value)


class Bool(Rule):
    def check(self, value: object, path: str, walk: _Walk) -> object:
        if not isinstance(value, bool):
            raise ChartSpecError(f"{_label(path)} must be true or false", path)
        return value

    def describe(self) -> str:
        return "boolean"


class Null(Rule):
    def check(self, value: object, path: str, walk: _Walk) -> object:
        if value is not None:
            raise ChartSpecError(f"{_label(path)} must be null", path)
        return value

    def describe(self) -> str:
        return "null"


class Enum(Rule):
    def __init__(self, values: Iterable[str]) -> None:
        self.values = frozenset(values)

    def check(self, value: object, path: str, walk: _Walk) -> object:
        # Type first: ``in`` on a frozenset raises for an unhashable value, and
        # a nested object must be a refusal, never a crash a caller sees as 500.
        if not isinstance(value, str) or value not in self.values:
            raise ChartSpecError(f"{_label(path)} must be one of {sorted(self.values)}", path)
        return value

    def describe(self) -> str:
        return f"one of {sorted(self.values)}"


class Registry(Rule):
    """An enum whose members are a profile registry, read at check time so a
    registration made after the rule was built still counts."""

    def __init__(self, pick: Callable[[Profile], Iterable[str]], what: str) -> None:
        self.pick = pick
        self.what = what

    def check(self, value: object, path: str, walk: _Walk) -> object:
        allowed = frozenset(self.pick(walk.profile))
        if not isinstance(value, str) or value not in allowed:
            raise ChartSpecError(f"{_label(path)} must be one of {sorted(allowed)}", path)
        return value

    def describe(self) -> str:
        return self.what


class Field(Rule):
    """A field name a chart reads. Recorded with its path for binding."""

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if not isinstance(value, str) or not value:
            raise ChartSpecError(f"{_label(path)} must be a non-empty string", path)
        if len(value) > MAX_FIELD_CHARS:
            raise ChartSpecError(
                f"{_label(path)} must be at most {MAX_FIELD_CHARS} characters", path
            )
        walk.fields.append((path, value))
        return value

    def describe(self) -> str:
        return "field name"


class Output(Rule):
    """A field name a transform creates (its ``as``)."""

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if not isinstance(value, str) or not value or len(value) > MAX_FIELD_CHARS:
            raise ChartSpecError(
                f"{_label(path)} must be a non-empty string of at most "
                f"{MAX_FIELD_CHARS} characters",
                path,
            )
        walk.produced.add(value)
        return value

    def describe(self) -> str:
        return "output field name"


PARAM_NAME = r"^[A-Za-z_][A-Za-z0-9_]{0,63}$"


class ParamRef(Rule):
    """A reference to a selection the spec declares."""

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if not isinstance(value, str) or not re.match(PARAM_NAME, value):
            raise ChartSpecError(f"{_label(path)} must name a declared selection", path)
        walk.param_refs.append((path, value))
        return value

    def describe(self) -> str:
        return "selection name"


class Const(Rule):
    def __init__(self, value: object) -> None:
        self.value = value

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if value != self.value or type(value) is not type(self.value):
            raise ChartSpecError(f"{_label(path)} must be {json.dumps(self.value)}", path)
        return value

    def describe(self) -> str:
        return json.dumps(self.value)


class Arr(Rule):
    def __init__(self, item: Rule, *, max_items: int = MAX_LIST, min_items: int = 0) -> None:
        self.item = item
        self.max_items = max_items
        self.min_items = min_items

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if not isinstance(value, list):
            raise ChartSpecError(f"{_label(path)} must be a list", path)
        if not self.min_items <= len(value) <= self.max_items:
            raise ChartSpecError(
                f"{_label(path)} must hold between {self.min_items} and {self.max_items} items",
                path,
            )
        return [self.item.check(item, _index(path, i), walk) for i, item in enumerate(value)]

    def describe(self) -> str:
        return f"list of {self.item.describe()}"


class Obj(Rule):
    """An object whose keys are exactly a subset of ``fields``."""

    def __init__(
        self,
        fields: Mapping[str, Rule],
        *,
        required: Sequence[str] = (),
        what: str = "object",
    ) -> None:
        self.fields = dict(fields)
        self.required = tuple(required)
        self.what = what

    def check(self, value: object, path: str, walk: _Walk) -> object:
        raw = _mapping(value, path)
        unknown = sorted(set(raw) - set(self.fields))
        if unknown:
            raise ChartSpecError(f"{_label(path)} carries unsupported keys: {unknown}", path)
        for key in self.required:
            if key not in raw:
                raise ChartSpecError(f"{_label(path)} must name {key}", _join(path, key))
        # Checked in the rule's order, so which refusal a spec earns does not
        # depend on how its writer happened to order its keys.
        checked = {
            key: self.fields[key].check(raw[key], _join(path, key), walk)
            for key in self.fields
            if key in raw
        }
        return {key: checked[key] for key in raw}

    def describe(self) -> str:
        return self.what


class OneOf(Rule):
    """The first alternative that admits the value. Alternatives are chosen
    by the value's JSON type so the refusal is the matching branch's own."""

    def __init__(self, *rules: Rule) -> None:
        self.rules = rules

    def check(self, value: object, path: str, walk: _Walk) -> object:
        kind = _json_kind(value)
        matching = [rule for rule in self.rules if kind in _accepts(rule)]
        if not matching:
            raise ChartSpecError(
                f"{_label(path)} must be {' or '.join(r.describe() for r in self.rules)}", path
            )
        if len(matching) == 1:
            return matching[0].check(value, path, walk)
        if isinstance(value, Mapping):
            # An object alternative whose required keys the value carries is
            # the one its writer meant, so its refusal is the one reported.
            keys = set(value)
            matching.sort(
                key=lambda r: not (isinstance(r, Obj) and r.required and set(r.required) <= keys)
            )
        first: ChartSpecError | None = None
        for rule in matching:
            trial = _Walk(walk.profile, walk.policy)
            try:
                rule.check(value, path, trial)
            except ChartSpecError as exc:
                first = first or exc
                continue
            return rule.check(value, path, walk)
        assert first is not None
        raise first

    def describe(self) -> str:
        return " or ".join(rule.describe() for rule in self.rules)


class Lazy(Rule):
    """A rule built on first use, for the recursive shapes (predicates, views)."""

    def __init__(self, build: Callable[[], Rule], what: str) -> None:
        self.build = build
        self.what = what
        self._rule: Rule | None = None

    def check(self, value: object, path: str, walk: _Walk) -> object:
        if self._rule is None:
            self._rule = self.build()
        return self._rule.check(value, path, walk)

    def describe(self) -> str:
        return self.what


class Custom(Rule):
    """A rule with its own check function, for the shapes keyed by a registry
    (marks, channels, transforms, views)."""

    def __init__(
        self, fn: Callable[[object, str, _Walk], object], what: str, kinds: Iterable[str]
    ) -> None:
        self.fn = fn
        self.what = what
        self.kinds = frozenset(kinds)

    def check(self, value: object, path: str, walk: _Walk) -> object:
        return self.fn(value, path, walk)

    def describe(self) -> str:
        return self.what


def _json_kind(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, (int, float)):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        return "array"
    if isinstance(value, Mapping):
        return "object"
    return "other"


def _accepts(rule: Rule) -> frozenset[str]:
    if isinstance(rule, (Str, Field, Output, ParamRef, Enum, Registry, Expression)):
        return frozenset({"string"})
    if isinstance(rule, Num):
        return frozenset({"number"})
    if isinstance(rule, Bool):
        return frozenset({"boolean"})
    if isinstance(rule, Null):
        return frozenset({"null"})
    if isinstance(rule, Const):
        return frozenset({_json_kind(rule.value)})
    if isinstance(rule, Arr):
        return frozenset({"array"})
    if isinstance(rule, Obj):
        return frozenset({"object"})
    if isinstance(rule, OneOf):
        out: set[str] = set()
        for inner in rule.rules:
            out |= _accepts(inner)
        return frozenset(out)
    if isinstance(rule, Custom):
        return rule.kinds
    return frozenset({"null", "boolean", "number", "string", "array", "object"})


def _mapping(value: object, path: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise ChartSpecError(f"{_label(path)} must be an object", path)
    for key in value:
        if not isinstance(key, str):
            raise ChartSpecError(f"{_label(path)} has a non-string key", path)
    return value


# --------------------------------------------------------------------------
# Registrations: what a mark, a channel and a transform are.
# --------------------------------------------------------------------------


class Transform:
    """One registered transform: the key that identifies it, the rule for its
    object, and the output fields it creates (``None``: it can create fields
    no static reading can name, so binding cannot be checked past it)."""

    def __init__(
        self,
        key: str,
        rule: Obj,
        outputs: Callable[[Mapping[str, Any]], Iterable[str] | None],
        note: str,
    ) -> None:
        self.key = key
        self.rule = rule
        self.outputs = outputs
        self.note = note


class Profile:
    """The registries a validation walks against.

    ``marks`` maps a mark name to the rule for the properties its object form
    may carry; ``channels`` maps an encoding channel to the rule for its
    definition; ``transforms`` maps the identifying key to a :class:`Transform`.
    """

    def __init__(self) -> None:
        self.marks: dict[str, dict[str, Rule]] = {}
        self.channels: dict[str, Rule] = {}
        self.transforms: dict[str, Transform] = {}
        self.aggregates: set[str] = set()
        self.time_units: set[str] = set()
        self.schemes: set[str] = set()
        self.interactions: dict[str, str] = {}
        self.expression_functions: set[str] = set()
        self.expression_constants: set[str] = set()

    def register_mark(self, name: str, props: Mapping[str, Rule]) -> None:
        self.marks[name] = dict(props)

    def register_channel(self, name: str, rule: Rule) -> None:
        self.channels[name] = rule

    def register_transform(self, transform: Transform) -> None:
        self.transforms[transform.key] = transform

    def summary(self) -> dict[str, Any]:
        """The vocabulary, for an author (a person reading docs, an agent
        reading its tool description)."""
        return {
            "profile": PROFILE_VERSION,
            "marks": sorted(self.marks),
            "channels": sorted(self.channels),
            "transforms": {key: t.note for key, t in sorted(self.transforms.items())},
            "aggregates": sorted(self.aggregates),
            "time_units": sorted(self.time_units),
            "schemes": sorted(self.schemes),
            "interactions": dict(sorted(self.interactions.items())),
            "expressions": {
                "functions": sorted(self.expression_functions),
                "constants": sorted(self.expression_constants),
                "reads": "datum.field or datum['field']",
            },
            "limits": {
                "inline_rows": MAX_INLINE_ROWS,
                "fields_per_row": MAX_ROW_FIELDS,
                "cell_chars": MAX_CELL_CHARS,
                "views": MAX_VIEWS,
                "layers": MAX_LAYERS,
                "transforms_per_view": MAX_TRANSFORMS,
                "dimension": MAX_DIMENSION,
                "expression_chars": MAX_EXPRESSION_CHARS,
                "expression_depth": MAX_EXPRESSION_DEPTH,
            },
        }


