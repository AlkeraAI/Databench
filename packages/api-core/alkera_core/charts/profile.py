class ValidatedChart:
    """An admitted spec and what the walk learned about it."""

    __slots__ = (
        "columns",
        "data_refs",
        "fields",
        "marks",
        "opaque_outputs",
        "params",
        "produced",
        "rows",
        "spec",
    )

    def __init__(self, spec: dict[str, Any], walk: _Walk) -> None:
        self.spec = spec
        self.fields: list[tuple[str, str]] = list(walk.fields)
        self.produced: frozenset[str] = frozenset(walk.produced)
        self.opaque_outputs = walk.opaque_outputs
        self.params: frozenset[str] = frozenset(walk.params)
        self.data_refs: list[tuple[str, str]] = list(walk.data_refs)
        self.columns: frozenset[str] = frozenset(walk.columns)
        self.marks: frozenset[str] = frozenset(walk.marks)
        self.rows = walk.rows

    def persisted(self) -> dict[str, Any]:
        """The spec as it is stored: the admitted keys, ``$schema`` named."""
        return dict(self.spec)

    def unbound_fields(self, columns: Iterable[str]) -> list[str]:
        """Paths of the fields this chart reads that neither ``columns`` nor a
        transform provides. Empty when a transform's outputs are data-dependent
        (pivot), since no static reading can name them."""
        if self.opaque_outputs:
            return []
        known = set(columns) | set(self.produced)
        return [path for path, name in self.fields if field_root(name) not in known]


def field_root(name: str) -> str:
    """The top-level column a Vega-Lite field reads: ``a.b`` reads column
    ``a`` (nested access), while ``a\\.b`` is the column literally named
    ``a.b``."""
    out: list[str] = []
    i = 0
    while i < len(name):
        ch = name[i]
        if ch == "\\" and i + 1 < len(name):
            out.append(name[i + 1])
            i += 2
            continue
        if ch in ".[":
            break
        out.append(ch)
        i += 1
    return "".join(out)


def escape_field(column: str) -> str:
    """A column name spelled as a Vega-Lite field that reads exactly it."""
    return re.sub(r"([.\[\]\\])", r"\\\1", column)


def validate(
    spec: object,
    *,
    policy: DataPolicy = INLINE,
    columns: Iterable[str] | None = None,
    profile: Profile | None = None,
) -> ValidatedChart:
    """``spec`` admitted by the profile, or :class:`ChartSpecError`.

    ``columns`` are the fields a host-bound table carries (a result's column
    keys); with them, a field nothing provides is refused. Under an inline
    policy the inline rows' own fields are the columns, so a typo is refused
    without the caller naming anything.
    """
    walk = _Walk(profile or PROFILE, policy)
    raw = _mapping(spec, "")
    admitted = _check_view(raw, "", walk)
    assert isinstance(admitted, dict)
    for path, name in walk.param_refs:
        if name not in walk.params:
            raise ChartSpecError(f"{path} names a selection the chart does not declare", path)
    for path, name in walk.data_refs:
        if name not in walk.dataset_names and not policy.host_tables:
            raise ChartSpecError(f"{path} names a dataset the chart does not carry", path)
    if "$schema" not in admitted:
        admitted = {"$schema": VEGA_LITE_V6_SCHEMA, **admitted}
    chart = ValidatedChart(admitted, walk)
    known: set[str] | None = None
    if columns is not None:
        known = set(columns)
    elif policy.inline and walk.rows and not (policy.host_tables and walk.data_refs):
        known = set(walk.columns)
    if known is not None:
        unbound = chart.unbound_fields(known)
        if unbound:
            raise ChartSpecError(
                f"{unbound[0]} names a field the chart's data does not have", unbound[0]
            )
    return chart


def spec_size(spec: Mapping[str, Any]) -> int:
    """The spec's size as compact JSON, in bytes."""
    return len(json.dumps(spec, separators=(",", ":"), ensure_ascii=False).encode("utf-8"))


