def _check_mark(value: object, path: str, walk: _Walk) -> object:
    marks = walk.profile.marks
    if isinstance(value, str):
        if value not in marks:
            raise ChartSpecError(f"{_label(path)} must be one of {sorted(marks)}", path)
        walk.marks.add(value)
        return value
    raw = _mapping(value, path)
    kind = raw.get("type")
    if not isinstance(kind, str) or kind not in marks:
        raise ChartSpecError(
            f"{_join(path, 'type')} must be one of {sorted(marks)}", _join(path, "type")
        )
    walk.marks.add(kind)
    rule = Obj({"type": Const(kind), **COMMON_MARK_PROPS, **marks[kind]}, what=f"{kind} mark")
    return rule.check(raw, path, walk)


